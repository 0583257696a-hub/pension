// Embeds the PDF fonts as base64 so the PDF renderer runs unchanged on Node and Cloudflare Workers.
import { readFileSync, writeFileSync } from "node:fs";

const files = {
  regular: "Heebo-Regular.ttf",
  bold: "Heebo-Bold.ttf",
  mathRegular: "DejaVuSans-Math-Regular.ttf",
  mathBold: "DejaVuSans-Math-Bold.ttf",
};
let out = "// Generated by scripts/build-pdf-fonts.mjs from assets/pdf-fonts. Do not edit.\n";
for (const [name, file] of Object.entries(files)) {
  const b64 = readFileSync(new URL(`../assets/pdf-fonts/${file}`, import.meta.url)).toString("base64");
  out += `export const ${name} = "${b64}";\n`;
}
writeFileSync(new URL("../src/academy/pdf/fonts.generated.ts", import.meta.url), out);
console.log("wrote src/academy/pdf/fonts.generated.ts");
